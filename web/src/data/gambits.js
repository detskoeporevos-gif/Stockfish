/* Плоский список вариантов — источник дебютной книги. */
export function gambitBookLines() {
    const out = [];
    for (const g of GAMBITS) {
        const lines = g.lines && g.lines.length ? g.lines : [g.moves];
        /* главная линия идёт первой — она приоритетна в книге */
        const ordered = [g.moves, ...lines];
        ordered.forEach((line, idx) => {
            if (!line) return;
            out.push({ id: g.id, moves: line, weight: idx === 0 ? 6 : Math.max(1, 4 - idx) });
        });
    }
    return out;
}

